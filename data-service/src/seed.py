"""
VetTrack Synthetic Data Generator.
Uses Faker to generate realistic synthetic clinical datasets:
- 200 owners
- 400 animals (Dogs, Cats, Cattle, Poultry)
- 1,500 vaccinations
- Associated visits and vet examinations

Never uses real client or animal information.
"""

import argparse
import random
from datetime import date, timedelta
from faker import Faker

fake = Faker()
Faker.seed(42)
random.seed(42)

SPECIES_BREEDS = {
    "Dog": ["Golden Retriever", "Labrador Retriever", "German Shepherd", "Beagle", "Bulldog", "Poodle", "Rottweiler", "Boxer"],
    "Cat": ["Domestic Shorthair", "Siamese", "Persian", "Maine Coon", "Ragdoll", "Bengal", "Sphynx"],
    "Cattle": ["Holstein Friesian", "Angus", "Hereford", "Jersey", "Brahman", "Simmental"],
    "Poultry": ["Leghorn", "Rhode Island Red", "Plymouth Rock", "Sussex", "Orpington", "Australorp"]
}

VACCINE_CATALOG = [
    {"id": 1, "name": "Rabies Core", "species": ["Dog", "Cat", "Cattle"], "interval": 365, "batches": [1, 2]},
    {"id": 2, "name": "DHPP 5-in-1", "species": ["Dog"], "interval": 365, "batches": [3]},
    {"id": 3, "name": "FVRCP Feline Core", "species": ["Cat"], "interval": 365, "batches": [5]},
    {"id": 4, "name": "Bovine Resp Shield 9", "species": ["Cattle"], "interval": 180, "batches": [6]},
    {"id": 5, "name": "Newcastle-Bronchitis Avian", "species": ["Poultry"], "interval": 90, "batches": [7]},
]

TEXAS_CITIES = ["Austin", "Round Rock", "Georgetown", "San Marcos", "Dallas", "Fort Worth", "Houston", "San Antonio", "Waco", "College Station", "El Paso", "Lubbock"]


def generate_seed_sql(num_owners=200, num_animals=400, num_vaccinations=1500, output_sql_path=None):
    lines = []
    lines.append("-- Generated by VetTrack Synthetic Seed Generator (Faker)")
    lines.append("-- Synthetic test data only. No real personal or clinical data.\n")

    # Generate Owners
    lines.append("-- Owners")
    owners = []
    for i in range(1, num_owners + 1):
        name = fake.name().replace("'", "''")
        phone = f"+1-{random.randint(200, 999)}-{random.randint(100, 999)}-{random.randint(1000, 9999)}"
        email = f"{fake.user_name()}{random.randint(10, 99)}@{fake.free_email_domain()}"
        city = random.choice(TEXAS_CITIES)
        owners.append((i, name, phone, email, city))
        lines.append(f"INSERT INTO owners (name, phone, email, city, created_at, updated_at) VALUES ('{name}', '{phone}', '{email}', '{city}', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);")

    # Generate Animals
    lines.append("\n-- Animals")
    animals = []
    today = date.today()
    for i in range(1, num_animals + 1):
        owner_id = random.randint(1, num_owners)
        species = random.choices(["Dog", "Cat", "Cattle", "Poultry"], weights=[40, 30, 20, 10])[0]
        breed = random.choice(SPECIES_BREEDS[species])
        name = fake.first_name().replace("'", "''")
        birth_date = today - timedelta(days=random.randint(60, 365 * 10))
        sex = random.choice(["Male", "Female"])
        animals.append((i, owner_id, species, birth_date))
        lines.append(f"INSERT INTO animals (owner_id, name, species, breed, birth_date, sex, created_at, updated_at) VALUES ({owner_id}, '{name}', '{species}', '{breed}', '{birth_date}', '{sex}', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);")

    # Generate Visits
    lines.append("\n-- Visits")
    visits = []
    reasons = ["Annual Wellness Checkup", "Routine Vaccination", "Limping / Injury", "Digestive Upset", "Skin / Ear Infection", "Pre-breeding Exam", "Herd Inspection"]
    num_visits = 800
    for v_id in range(1, num_visits + 1):
        animal = random.choice(animals)
        animal_id = animal[0]
        vet_id = random.randint(1, 3)
        visit_date = today - timedelta(days=random.randint(1, 500))
        reason = random.choice(reasons)
        notes = f"Patient presented for {reason.lower()}. Vitals stable. Treatment administered."
        visits.append((v_id, animal_id, visit_date))
        lines.append(f"INSERT INTO visits (animal_id, vet_id, visit_date, reason, notes, created_at, updated_at) VALUES ({animal_id}, {vet_id}, '{visit_date}', '{reason}', '{notes}', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);")

    # Generate Vaccinations
    lines.append("\n-- Vaccinations")
    for vac_id in range(1, num_vaccinations + 1):
        animal = random.choice(animals)
        animal_id = animal[0]
        species = animal[2]
        birth_date = animal[3]

        compatible_vaccines = [v for v in VACCINE_CATALOG if species in v["species"]]
        if not compatible_vaccines:
            continue

        selected_vaccine = random.choice(compatible_vaccines)
        batch_id = random.choice(selected_vaccine["batches"])
        vaccine_id = selected_vaccine["id"]
        interval = selected_vaccine["interval"]

        # Given date between animal birth and today
        days_alive = max(30, (today - birth_date).days)
        given_on = birth_date + timedelta(days=random.randint(30, days_alive))
        next_due_on = given_on + timedelta(days=interval)

        visit_id = "NULL"
        if random.random() < 0.6 and visits:
            visit_id = str(random.choice(visits)[0])

        lines.append(f"INSERT INTO vaccinations (animal_id, vaccine_id, batch_id, given_on, next_due_on, visit_id, created_at, updated_at) VALUES ({animal_id}, {vaccine_id}, {batch_id}, '{given_on}', '{next_due_on}', {visit_id}, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);")

    sql_content = "\n".join(lines) + "\n"

    if output_sql_path:
        with open(output_sql_path, "w", encoding="utf-8") as f:
            f.write(sql_content)
        print(f"Generated {output_sql_path} with {num_owners} owners, {num_animals} animals, and {num_vaccinations} vaccinations.")

    return sql_content


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="VetTrack Synthetic Data Seed Generator")
    parser.add_argument("--owners", type=int, default=200, help="Number of synthetic owners")
    parser.add_argument("--animals", type=int, default=400, help="Number of synthetic animals")
    parser.add_argument("--vaccinations", type=int, default=1500, help="Number of synthetic vaccinations")
    parser.add_argument("--out", type=str, default="data-service/raw/seed_synthetic.sql", help="Output SQL file path")

    args = parser.parse_args()
    generate_seed_sql(args.owners, args.animals, args.vaccinations, args.out)
